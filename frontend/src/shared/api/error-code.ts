import type { components } from './schema'

export type ErrorCode = components['schemas']['ErrorCode']

const ERROR_CODE_MAP = {
  EMAIL_TAKEN: 'EMAIL_TAKEN',
  INVALID_CREDENTIALS: 'INVALID_CREDENTIALS',
  CATALOG_ITEM_NOT_FOUND: 'CATALOG_ITEM_NOT_FOUND',
  INVALID_SCHEDULE: 'INVALID_SCHEDULE',
  LOT_NOT_FOUND: 'LOT_NOT_FOUND',
  LOT_NOT_CANCELLABLE: 'LOT_NOT_CANCELLABLE',
  LOT_NOT_STARTED: 'LOT_NOT_STARTED',
  LOT_CLOSED: 'LOT_CLOSED',
  ALREADY_WINNING: 'ALREADY_WINNING',
  BELOW_MINIMUM: 'BELOW_MINIMUM',
  INSUFFICIENT_FUNDS: 'INSUFFICIENT_FUNDS',
  RECEIPT_NOT_FOUND: 'RECEIPT_NOT_FOUND',
  IDEMPOTENCY_KEY_REQUIRED: 'IDEMPOTENCY_KEY_REQUIRED',
  IDEMPOTENCY_KEY_INVALID: 'IDEMPOTENCY_KEY_INVALID',
  IDEMPOTENCY_KEY_REUSED: 'IDEMPOTENCY_KEY_REUSED',
  REQUEST_IN_PROGRESS: 'REQUEST_IN_PROGRESS',
} as const satisfies { [K in ErrorCode]: K }

export const ERROR_CODES = Object.values(ERROR_CODE_MAP)

const ERROR_CODE_SET: ReadonlySet<string> = new Set(ERROR_CODES)

export function isErrorCode(value: string): value is ErrorCode {
  return ERROR_CODE_SET.has(value)
}
